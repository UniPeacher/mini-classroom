/** 用户可调整的两份内容引导词：教程怎么讲，配图怎么表达。 */
export interface ContentGuidance {
  tutorialGuidance: string;
  figureGuidance: string;
}

/** 每份引导词的最大字数，前后端共用。 */
export const GUIDANCE_MAX_LENGTH = 12000;

/**
 * 写给学习者的内容（讲解、题目、批改反馈）共用的写作原则，目标是清晰、好读、容易理解。
 *
 * 整理自两份 MIT 许可的提示词，只取与"写内容"相关的部分，并按学习场景改写：
 * - i-have-adhd：工作记忆小、开头即要点、编号步骤、不跑题、列表不超过 5 项、去掉客套与复述
 * - gpt-with-taste（https://github.com/NB-Corp/gpt-with-taste）"Make taste visible" 与
 *   "Write for the reader's next action"：先取舍再成文、从熟悉情境切入、标题揭示要点、
 *   示例只演示一件事、按读者此刻需要选材、不写免责声明（参照 ISO 24495-1 平实语言原则）
 * i-have-adhd 原本针对对话回复，没有讲解排版的条款；"排版"一节把"工作记忆小、一眼抓住重点"落成
 * 带数字、可自查的规则（句长、段长、并列内容成列表、加粗锚点），因为"句子短"这类说法模型执行得很松。
 */
const DEFAULT_TUTORIAL_GUIDANCE = `## 写作原则（目标：清晰、好读、容易理解）

### 先取舍，再动笔
- 先决定保留什么、强调什么、删掉什么，定好主线和层次，再选形式。
- 只写学习者此刻理解这个知识点需要的内容。相关但不必要的延伸、历史和冷门细节不写。
- 学习者已学过的前置知识不再重复讲，直接拿来用。
- 讲清楚就停。决定结论的机制和理由要讲到，多余的铺垫和重复要删。

### 开头和结构
- 第一句就给出要点：它是什么、解决什么问题。不铺垫背景，不写"本节我们将学习……"。
- 从学习者熟悉的情境，或一个看得见的结果切入，再补上必要的概念。
- 小标题直接写出这一段的结论，例如"### unknown 必须先收窄才能用"，不用"概述""详解"这类空标题。
- 多步骤的过程用编号列表，每步只做一件事。
- 任何列表不超过 5 项；更多时先分组。
- 表格只用于需要并排比较的内容，例如易混概念的对比。
- 结尾不复述全文。需要收尾时，用一句话点出最容易错的地方，或给一个马上能动手试的小动作。

### 排版：扫一眼就能抓住重点（逐条执行）
- 一句话不超过 30 个字（代码、行内代码不算）。超过就拆成两句。
- 不用分号把几个意思串成一句。要说两件以上的事，就拆成几句，或写成列表。
- 一段只讲一件事，最多 3 句。超过就拆段，或改写成列表。
- 两条以上并列的规则、条件、情况或用法，写成列表，一条一行；条目之间有对应关系时（比如"参数个数 → 写法"），写成表格。
- 每段加粗 1~2 处最关键的词或短语：结论、决定结果的条件、最容易错的地方。只读加粗的部分，也能串起主线。不加粗整句，不加粗代码。
- 代码示例后，用列表逐条点出要看的地方，每条对应代码里的一处。

排版示例。改写前：
> 箭头函数常用于处理前端事件或转换后端返回的数据。没有参数时必须写 ()；一个参数可以省略括号；多个参数必须写括号。函数体只有一个表达式时可以省略 {}，表达式的值会自动返回，使用 {} 后必须写 return。

改写后：
> 箭头函数常用来**处理前端事件**，或**转换后端返回的数据**。
>
> 括号按参数个数决定：
>
> | 参数个数 | 写法 |
> |---|---|
> | 0 个 | \`() => 1\`，**必须写 ()** |
> | 1 个 | \`n => n * 2\`，括号可省 |
> | 2 个及以上 | \`(a, b) => a + b\`，必须写括号 |
>
> 函数体只有一个表达式时，可以省略 {}，**值会自动返回**。写了 {}，就**必须写 return**。

### 示例
- 每个示例只演示一个要点，去掉与这个要点无关的代码和铺垫。
- 示例要完整到能直接看懂，不让学习者去补全省略的部分。

### 照顾有限的工作记忆
- 需要的信息就放在用到它的地方。不写"记住上面的……""如前所述"。
- 同一个概念始终用同一个名称，不换同义词。
- 条件和例外只在它改变结论的地方说一次。

### 措辞
- 一句只说一件事。用具体的词、数字和例子，不用"一些""很多""某种程度上"。
- 删掉不提供信息的修饰语和含糊副词；真实存在的不确定要明说。
- 不用套话、成语和空洞的比喻。类比讲解中的类比除外，但要讲清类比与知识点的对应关系。
- 讲错误和误区时就事论事：错在哪、为什么错、正确做法是什么。
- 不写客套话、自我评价、免责声明和重复的边界说明。

### 自检（写完逐条检查，不合格就改）
- 只读第一句和最后一句，学习者能否抓住这个知识点的核心？
- 有没有超过 30 字的句子、用分号串起的句子、超过 3 句的段落？
- 并列的规则或情况，是不是已经写成列表或表格？
- 每段有没有加粗最关键的 1~2 处？只读加粗能不能串起主线？

### 篇幅与阅读顺序
- 讲解一般 200~500 字，不含代码和图；根据知识难度与学习基础调整详略。
- 按本节采用的讲解形式组织内容，让概念、例子、理由和易错点形成清楚的阅读顺序。`;

const DEFAULT_FIGURE_GUIDANCE = `配图的目的是帮助学习者理解知识。根据知识内容、知识类型、学习目标、已有基础和容易误解的地方，先判断配图能发挥什么作用，再决定哪些信息值得视觉化、如何组织、采用什么表达形式和视觉风格。

教学作用的参考：
- 建立第一印象：开门见山地呈现核心概念、典型情境或整体面貌，让学习者迅速知道正在学习什么。
- 形成直观理解：通过具体实例、空间关系、形象化表现或恰当类比，让抽象概念容易感知和理解。
- 呈现过程与机制：把复杂流程、时间顺序、条件分支、状态变化或因果关系组织成可观察、可追踪的过程。
- 突出关系与差异：帮助学习者看清组成、层次、联系、边界，以及容易混淆之处。
- 综合组织知识：将整体与局部、概念与实例、过程与结果等相关信息组合起来，形成连贯的理解。

这些作用可按需要选择、组合或采用其他更合适的方式，无须逐项覆盖。一张图可以同时承担多个相互配合的教学作用，例如用整体场景建立印象、用箭头展现过程、用局部放大解释细节、用对照突出差异。

表达与组织：
- 根据要表达的信息选择场景图、结构图、流程图、对照图、分镜、关系图、数据图、带注释的实例或其他形式，也可以组合。看清具体关系后再选择，学科名称本身不能决定画法。
- 明确重点、层次和阅读路径。需要比较的内容便于对照，需要连续理解的内容便于追踪，细节能找到对应的整体位置。必要时在图前或图后用一句话引导阅读。
- 构图、色彩、形状、空间感、细节和标注方式都服务于知识表达，视觉复杂度与教学价值相匹配。整体组织清楚，同一含义保持一致的视觉标记。
- 图中的概念、关系、条件、数据和符号准确，与正文术语一致。类比保持关键对应关系，示意数据明确标注；图中文字用简体中文，专业名称、代码和数学符号保持原文。
- 文字与图形在学习页的实际展示尺寸下清晰可读。信息过多时先分组、分步或拆图，保留决定理解的内容。

完成后检查：学习者能从图中获得什么理解？重点是否容易发现？各部分之间的关系是否清楚？是否存在可能造成误解的表现？据此调整配图。`;

/** 未自定义时采用的完整引导词。 */
export const DEFAULT_CONTENT_GUIDANCE: Readonly<ContentGuidance> = {
  tutorialGuidance: DEFAULT_TUTORIAL_GUIDANCE,
  figureGuidance: DEFAULT_FIGURE_GUIDANCE,
};

/** 将用户的默认选择解析成生成时使用的完整引导词。 */
export function resolveContentGuidance(settings: { tutorialGuidance: string | null; figureGuidance: string | null }): ContentGuidance {
  return {
    tutorialGuidance: settings.tutorialGuidance ?? DEFAULT_CONTENT_GUIDANCE.tutorialGuidance,
    figureGuidance: settings.figureGuidance ?? DEFAULT_CONTENT_GUIDANCE.figureGuidance,
  };
}

/** 判断生成中的内容是否仍对应当前引导词。 */
export function sameContentGuidance(left: ContentGuidance, right: ContentGuidance): boolean {
  return left.tutorialGuidance === right.tutorialGuidance && left.figureGuidance === right.figureGuidance;
}
