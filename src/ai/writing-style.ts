export const WRITING_PRINCIPLES = `## 写作原则（目标：清晰、好读、容易理解）

### 先取舍，再动笔
- 先决定保留什么、强调什么、删掉什么，定好主线和层次，再选形式。
- 只写学习者此刻理解这个知识点需要的内容。相关但不必要的延伸、历史和冷门细节不写。
- 学习者已学过的前置知识不再重复讲，直接拿来用。
- 讲清楚就停。决定结论的机制和理由要讲到，多余的铺垫和重复要删。

### 开头和结构
- 第一句就给出要点：它是什么、解决什么问题。不铺垫背景，不写"本节我们将学习……"。
- 从学习者熟悉的情境，或一个看得见的结果切入，再补上必要的概念。
- 小标题直接写出这一段的结论，例如"### unknown 必须先收窄才能用"，不用"概述""详解"这类空标题。
- 多步骤的过程用编号列表，每步只做一件事。
- 任何列表不超过 5 项；更多时先分组。
- 表格只用于需要并排比较的内容，例如易混概念的对比。
- 结尾不复述全文。需要收尾时，用一句话点出最容易错的地方，或给一个马上能动手试的小动作。

### 排版：扫一眼就能抓住重点（逐条执行）
- 一句话不超过 30 个字（代码、行内代码不算）。超过就拆成两句。
- 不用分号把几个意思串成一句。要说两件以上的事，就拆成几句，或写成列表。
- 一段只讲一件事，最多 3 句。超过就拆段，或改写成列表。
- 两条以上并列的规则、条件、情况或用法，写成列表，一条一行；条目之间有对应关系时（比如"参数个数 → 写法"），写成表格。
- 每段加粗 1~2 处最关键的词或短语：结论、决定结果的条件、最容易错的地方。只读加粗的部分，也能串起主线。不加粗整句，不加粗代码。
- 代码示例后，用列表逐条点出要看的地方，每条对应代码里的一处。

排版示例。改写前：
> 箭头函数常用于处理前端事件或转换后端返回的数据。没有参数时必须写 ()；一个参数可以省略括号；多个参数必须写括号。函数体只有一个表达式时可以省略 {}，表达式的值会自动返回，使用 {} 后必须写 return。

改写后：
> 箭头函数常用来**处理前端事件**，或**转换后端返回的数据**。
>
> 括号按参数个数决定：
>
> | 参数个数 | 写法 |
> |---|---|
> | 0 个 | \`() => 1\`，**必须写 ()** |
> | 1 个 | \`n => n * 2\`，括号可省 |
> | 2 个及以上 | \`(a, b) => a + b\`，必须写括号 |
>
> 函数体只有一个表达式时，可以省略 {}，**值会自动返回**。写了 {}，就**必须写 return**。

### 示例
- 每个示例只演示一个要点，去掉与这个要点无关的代码和铺垫。
- 示例要完整到能直接看懂，不让学习者去补全省略的部分。

### 照顾有限的工作记忆
- 需要的信息就放在用到它的地方。不写"记住上面的……""如前所述"。
- 同一个概念始终用同一个名称，不换同义词。
- 条件和例外只在它改变结论的地方说一次。

### 措辞
- 一句只说一件事。用具体的词、数字和例子，不用"一些""很多""某种程度上"。
- 删掉不提供信息的修饰语和含糊副词；真实存在的不确定要明说。
- 不用套话、成语和空洞的比喻。类比讲解中的类比除外，但要讲清类比与知识点的对应关系。
- 讲错误和误区时就事论事：错在哪、为什么错、正确做法是什么。
- 不写客套话、自我评价、免责声明和重复的边界说明。

### 自检（写完逐条检查，不合格就改）
- 只读第一句和最后一句，学习者能否抓住这个知识点的核心？
- 有没有超过 30 字的句子、用分号串起的句子、超过 3 句的段落？
- 并列的规则或情况，是不是已经写成列表或表格？
- 每段有没有加粗最关键的 1~2 处？只读加粗能不能串起主线？`;

